#!/usr/bin/env bun
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const output = join(root, "skills", "ggh", "reference.md");

function object(value: unknown): Record<string, unknown> {
  if (!value || typeof value !== "object" || Array.isArray(value)) throw new Error("Expected a schema object");
  return Object.fromEntries(Object.entries(value));
}
function strings(value: unknown): string[] {
  if (!Array.isArray(value) || !value.every(item => typeof item === "string")) throw new Error("Expected schema strings");
  return value;
}
function cell(value: unknown): string {
  return String(value).replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}
function literal(value: unknown): string {
  return `\`${cell(JSON.stringify(value))}\``;
}
function fieldRows(value: unknown, path = "", required = false): string[] {
  const schema = object(value);
  const rows: string[] = [];
  const type = schema.const !== undefined ? literal(schema.const) : schema.enum ? literal(schema.enum)
    : Array.isArray(schema.type) ? schema.type.join(" / ") : schema.type ?? "varies";
  if (path) rows.push(`| \`${path}\` | ${cell(type)} | ${required ? "yes" : "no"} | ${schema.default === undefined ? "" : literal(schema.default)} | ${cell(schema.description ?? "")} |`);
  if (schema.properties) {
    const mandatory = schema.required ? strings(schema.required) : [];
    for (const [key, child] of Object.entries(object(schema.properties))) {
      rows.push(...fieldRows(child, path ? `${path}.${key}` : key, mandatory.includes(key)));
    }
  }
  if (schema.items && !Array.isArray(schema.items)) rows.push(...fieldRows(schema.items, `${path}[]`));
  for (const keyword of ["anyOf", "oneOf", "allOf"]) {
    const variants = schema[keyword];
    if (Array.isArray(variants)) for (const [index, variant] of variants.entries()) {
      rows.push(...fieldRows(variant, path ? `${path} [${keyword} ${index + 1}]` : `[${keyword} ${index + 1}]`, required));
    }
  }
  return rows;
}
const header = "| Field | Type / values | Required in parent | Default | Meaning |\n| --- | --- | --- | --- | --- |";

export async function generateSkillReference(): Promise<string> {
  // User aliases can override built-ins. Discover the command contract without
  // loading a user's aliases, plugins, or configuration.
  const home = mkdtempSync(join(tmpdir(), "ggh-skill-schema-"));
  try {
    const child = Bun.spawn([process.execPath, "run", join(root, "bin", "ggh.ts"), "agent", "schema"], {
      cwd: root, env: { ...process.env, HOME: home, USERPROFILE: home, XDG_CONFIG_HOME: home, GGH_CONFIG_DIR: join(home, "good-gh"), GGH_NO_PLUGINS: "1" }, stdin: "ignore", stdout: "pipe", stderr: "pipe",
    });
    const [stdout, stderr, code] = await Promise.all([new Response(child.stdout).text(), new Response(child.stderr).text(), child.exited]);
    if (code !== 0 || stderr) throw new Error(`ggh agent schema failed: ${stderr || stdout}`);
    const schema = object(JSON.parse(stdout));
    const core = object(schema.coreResultSchemas);
    if (!Array.isArray(schema.supportedCommandPaths) || !Array.isArray(schema.inputs)) throw new Error("Missing command catalog");
    const lines = ["<!-- Generated by bun run scripts/gen-skill-reference.ts from ggh agent schema. Do not edit. -->", "# ggh agent reference", "", "All fields below come from the installed command tree and result schemas. Required fields apply within their parent object or alternative. Array items and schema alternatives have separate rows. These tables summarize fields; use `ggh agent schema --agent` for full JSON Schema constraints.", "", "## Envelope", "", header, ...fieldRows(schema.envelope), "", "## Commands", "", "Every managed command accepts `--agent`. It wraps this payload in `result` and disables prompts. Schemas cover only the listed fields; unspecified payloads are not stable field contracts.", "", "| Command | Arguments | Options | Result schema |", "| --- | --- | --- | --- |"];
    for (const entry of schema.inputs) {
      const input = object(entry);
      const path = strings(input.path);
      if (!Array.isArray(input.arguments) || !Array.isArray(input.options)) throw new Error("Invalid command inputs");
      const matches = Object.entries(core).flatMap(([name, raw]) => {
        if (typeof raw === "string") return [];
        const result = object(raw);
        if (!Array.isArray(result.commandPaths)) throw new Error("Missing result command paths");
        return result.commandPaths.some(candidate => {
          const prefix = strings(candidate);
          return prefix.every((part, index) => path[index] === part) && (result.includesSubcommands || prefix.length === path.length);
        }) ? [`[${name}](#${name.toLowerCase()})`] : [];
      });
      const args = input.arguments.map(raw => {
        const argument = object(raw);
        return `${argument.required ? "<" : "["}${argument.name}${argument.variadic ? "..." : ""}${argument.required ? ">" : "]"}`;
      });
      const options = input.options.map(raw => { const option = object(raw); return `${option.long ?? option.short}${option.takesValue ? " value" : ""}`; });
      lines.push(`| \`ggh ${path.join(" ")}\` | ${args.length ? `\`${cell(args.join(" "))}\`` : ""} | ${cell(options.join(", "))} | ${matches.join(", ") || "Unspecified"} |`);
    }
    lines.push("", `Coverage: ${core.coverage}`, "");
    for (const [name, raw] of Object.entries(core)) {
      if (typeof raw === "string") continue;
      const result = object(raw);
      lines.push(`## ${name}`, "", header, ...fieldRows(result.schema, "result"), "");
    }
    return lines.join("\n");
  } finally { rmSync(home, { recursive: true, force: true }); }
}

if (import.meta.main) {
  const generated = await generateSkillReference();
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(output, "utf8"); } catch { /* Missing is stale. */ }
    if (current.replace(/\r\n/g, "\n") !== generated) {
      console.error("skills/ggh/reference.md is stale. Run bun run scripts/gen-skill-reference.ts.");
      process.exitCode = 1;
    } else console.error("skills/ggh/reference.md is fresh.");
  } else {
    mkdirSync(join(root, "skills", "ggh"), { recursive: true });
    writeFileSync(output, generated);
    console.error(`wrote ${output}`);
  }
}
